"""Rebuild Supplementary Table S6 inline, with the corrected readout statistic.

The published S6 is an external PDF that (i) reports the per-seed audit kappa in the
released trace form and (ii) asserts that "all four seeds fall within the
vanilla-equivalent region [0.78, 1.23]".  Both need updating: the band is now
[0.937, 1.064] in the corrected statistic, and the trace form is not basis-invariant.

Every ingredient survives:
  * GRQ / CTCP specificity  -- transcribed from the published table (their own
    sources are data/optionA_grq_decoder_traversal.json and
    data/ctcp_pure_validation.json; the published values are carried over unchanged)
  * trace kappa             -- data/grq_seeds_s9s12_kappa.json
  * corrected kappa         -- recomputed here from the same-seed checkpoint pairs
    (gvae_s{9..12}.pt vs vanilla_s{9..12}.pt) on the shared R14 iter-4 expression

Reads  : data/grq_seeds_s9s12_kappa.json
Writes : supplementary/table_s6_body.tex
Usage  : python code/make_tabS6.py [--cells 2000]
"""
from __future__ import annotations

import argparse
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER1 = os.path.abspath(os.path.join(HERE, ".."))
OUT = os.path.join(PAPER1, "supplementary", "table_s6_body.tex")

NEXT_PHASE = r"F:/UNAGI_Project/next_phase"
SCAN = os.path.join(NEXT_PHASE, "results", "gvae_hema_scan")
H5AD = (r"F:/UNAGI_Project/UNAGI/result/R14/R14_hemato_vanilla/iter_4"
        r"/stagedata/dataset.h5ad")

SEEDS = ["s9", "s10", "s11", "s12"]
GRQ = {"s9": 11.45, "s10": 13.83, "s11": 16.80, "s12": 11.32}
CTCP = {"s9": 19.2, "s10": 19.4, "s11": 18.8, "s12": 19.6}
BAND = (0.937, 1.064)


def load_X(n_cells):
    import h5py
    import scipy.sparse as sp
    with h5py.File(H5AD, "r") as f:
        X = f["X"]
        if isinstance(X, h5py.Group):
            M = sp.csr_matrix((X["data"][:], X["indices"][:], X["indptr"][:]),
                              shape=tuple(X.attrs["shape"]))
        else:
            M = np.asarray(X)
    M = M[:n_cells]
    return np.asarray(M.todense() if sp.issparse(M) else M, dtype=np.float32)


def readout(ckpt, X, device):
    """(trace form, corrected form) for one G-VAE checkpoint."""
    import torch
    sys.path.insert(0, NEXT_PHASE)
    from ptvae.gvae_model import GVAE
    from sklearn.linear_model import Ridge
    from sklearn.preprocessing import StandardScaler

    model = GVAE(n_genes=X.shape[1], n_latent=64, n_hidden=512, n_layers=2).to(device)
    model.load_state_dict(torch.load(ckpt, map_location=device,
                                     weights_only=False)["model"])
    model.eval()
    with torch.no_grad():
        Z = model.get_latent(torch.tensor(X, dtype=torch.float32).to(device))
    del model
    Z = np.asarray(Z.detach().cpu().numpy(), dtype=np.float64)
    Zs = StandardScaler().fit_transform(Z)
    Xs = StandardScaler().fit_transform(X.astype(np.float64))
    A = Ridge(alpha=1.0, fit_intercept=False).fit(Zs, Xs).coef_
    tr = float((A ** 2).sum())
    r2 = float(Xs.shape[1] - ((Xs - Zs @ A.T) ** 2).sum() / Xs.shape[0])
    return tr, r2


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cells", type=int, default=2000)
    args = ap.parse_args()

    import torch
    device = "cuda" if torch.cuda.is_available() else "cpu"
    X = load_X(args.cells)
    print(f"device={device}  X {X.shape}")

    pub = json.load(open(os.path.join(PAPER1, "data", "grq_seeds_s9s12_kappa.json"),
                         encoding="utf-8-sig"))

    rows, cache = [], {}
    print(f"\n{'seed':<6}{'k trace(pub)':>14}{'k corrected':>13}{'k trace(new)':>14}")
    for s in SEEDS:
        d = pub[s]
        k_tr_pub = d["kappa"]
        tr_g, r2_g = readout(os.path.join(SCAN, f"gvae_s{s[1:]}.pt"), X, device)
        tr_v, r2_v = readout(os.path.join(SCAN, f"vanilla_s{s[1:]}.pt"), X, device)
        k_tr_new = tr_g / tr_v
        k_r2 = r2_g / r2_v
        rows.append(dict(seed=s, grq=GRQ[s], ctcp=CTCP[s], k_tr_pub=k_tr_pub,
                         k_tr_new=k_tr_new, k_r2=k_r2, C_r2=(1 - k_r2) * 100))
        print(f"{s:<6}{k_tr_pub:>14.4f}{k_r2:>13.4f}{k_tr_new:>14.4f}")

    lines = [
        "% AUTO-GENERATED by code/make_tabS6.py -- do not edit by hand.",
        r"\begin{tabular}{@{}lrrrrl@{}}",
        r"\toprule",
        r"\textbf{Seed} & \textbf{GRQ ($\times$)} & \textbf{CTCP ($\times$)}"
        r" & \multicolumn{2}{c}{\textbf{$\kappa$-$C(W)$}} & \textbf{Regime} \\",
        r"\cmidrule(lr){4-5}",
        r" & & & trace & corrected & corrected \\",
        r"\midrule",
    ]
    for r in rows:
        k = r["k_r2"]
        reg = ("sub-vanilla" if k < BAND[0] else
               "van-equiv." if k <= BAND[1] else "expanded")
        lines.append(
            f"{r['seed']} & {r['grq']:.2f} & {r['ctcp']:.1f} & "
            f"{r['k_tr_pub']:.3f} & {r['k_r2']:.4f} & {reg} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"\n[wrote] {OUT}")
    k = np.array([r["k_r2"] for r in rows])
    kt = np.array([r["k_tr_new"] for r in rows])
    print(f"  corrected kappa range {k.min():.4f} -- {k.max():.4f}  "
          f"(trace {kt.min():.3f} -- {kt.max():.3f})")
    print(f"  inside corrected cross-family band {BAND}: "
          f"{int(((k >= BAND[0]) & (k <= BAND[1])).sum())}/4")


if __name__ == "__main__":
    main()
