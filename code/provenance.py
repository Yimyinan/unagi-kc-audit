"""provenance.py -- attach a self-describing provenance block to a derived artefact.

Why this exists
---------------
Report A found that the paper1 audit code was never version-controlled and that the
released artefacts carry no record of how they were made.  Two generator scripts even
had mtimes NEWER than their own outputs, so the code text could not be shown to be the
generating text.

This module closes that gap for every artefact written from now on: the JSON itself
records which script wrote it, its hash, the git state at run time, and the hashes of
its inputs.  A reader can then verify the link without trusting anyone's word.

Usage
-----
    from provenance import attach
    out = {...}                      # your payload
    out = attach(out, script=__file__, inputs=[SOME_CSV, ANOTHER_JSON])
    json.dump(out, open(dest, "w"), indent=1)

The block is added under the key ``_provenance``.  Payload keys are never modified, so
downstream readers that index specific keys keep working.
"""
from __future__ import annotations

import hashlib
import json
import os
import platform
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

__all__ = ["attach", "file_sha256", "git_state"]

_REPO = None


def _find_repo(start):
    """Walk up from `start` looking for a .git directory."""
    global _REPO
    if _REPO is not None:
        return _REPO
    p = Path(start).resolve()
    for parent in [p] + list(p.parents):
        if (parent / ".git").exists():
            _REPO = parent
            return _REPO
    _REPO = None
    return None


def file_sha256(path, chunk=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        while True:
            b = fh.read(chunk)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def git_state(start):
    repo = _find_repo(start)
    if repo is None:
        return {"repo": None, "note": "no .git found above this file"}

    def g(*args):
        try:
            r = subprocess.run(["git", *args], cwd=repo, capture_output=True, text=True,
                               encoding="utf-8", errors="replace", timeout=20)
            return r.stdout.strip()
        except Exception as exc:                            # noqa: BLE001
            return "<error: %s>" % exc

    dirty = g("status", "--porcelain")
    return {
        "repo": str(repo),
        "head": g("rev-parse", "HEAD") or None,
        "head_date": g("log", "-1", "--format=%ad", "--date=iso") or None,
        "describe": g("describe", "--tags", "--always", "--dirty") or None,
        "dirty": bool(dirty),
        "dirty_files": len([l for l in dirty.split("\n") if l.strip()]),
    }


def attach(payload, script=None, inputs=(), extra=None):
    """Return `payload` with a ``_provenance`` block appended.

    Parameters
    ----------
    payload : dict
        The artefact body.  Not mutated; a copy is returned.
    script : str
        Usually ``__file__`` -- the script writing the artefact.
    inputs : sequence of str or Path
        Files this artefact was derived from.  Each is hashed.
    extra : dict, optional
        Anything else worth recording (units, thresholds, seeds).
    """
    script = str(script or sys.argv[0] or "<unknown>")
    script_path = Path(script).resolve() if os.path.isfile(script) else None

    inblock = []
    for it in inputs:
        ip = Path(it)
        if ip.is_file():
            inblock.append({"path": str(ip), "sha256": file_sha256(ip),
                            "bytes": ip.stat().st_size})
        else:
            inblock.append({"path": str(ip), "error": "not found"})

    prov = {
        "schema": "paper1-artefact-provenance/1",
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "script": {
            "path": script,
            "sha256": file_sha256(script_path) if script_path else None,
            "bytes": script_path.stat().st_size if script_path else None,
            "mtime_utc": (datetime.fromtimestamp(script_path.stat().st_mtime,
                                                 timezone.utc).isoformat()
                          if script_path else None),
        },
        "git": git_state(script_path.parent if script_path else "."),
        "inputs": inblock,
        "runtime": {
            "python": sys.version.split()[0],
            "platform": platform.platform(),
            "executable": sys.executable,
        },
        "note": ("Generated by code/provenance.py. This block lets a reader check which "
                 "script produced the artefact and from which inputs, without relying on "
                 "file modification times."),
    }
    if extra:
        prov["extra"] = extra

    out = dict(payload) if isinstance(payload, dict) else {"payload": payload}
    out["_provenance"] = prov
    return out
