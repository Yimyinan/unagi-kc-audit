# -*- coding: utf-8 -*-
"""Generate the body of Supplementary Table S11 from the re-derived scVI/pbmc3k audit.

The table previously hand-written into supplementary.tex reported the published pair
(0.87 / 1.08 / +24.6%) as a cross-architecture validation.  That pair turned out to be
two fits of one model: the prior was registered with ``labels_key``, which does not
condition SCVI (see code/s1m3_scvi_injection_probe.py), so the two arms are
bit-identical and the numbers are seed noise.

Reads  : s1m_pbmc3k_seed_band.json (10 vanilla seeds, labels_key arm)
         s1m4_pbmc3k_injection.json (6 paired seeds, categorical-covariate arm)
         s1m5_pbmc3k_verdict.json  (z-scores and the paired difference)
Writes : supplementary/table_s11_body.tex
Usage  : python code/make_tabS11.py
"""
from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER1 = os.path.abspath(os.path.join(HERE, ".."))
ROOT = os.path.abspath(os.path.join(PAPER1, "..", ".."))
OUT = os.path.join(ROOT, "outputs", "positive_result")
DEST = os.path.join(PAPER1, "supplementary", "table_s11_body.tex")


def load(n):
    with open(os.path.join(OUT, n), encoding="utf-8") as f:
        return json.load(f)


def num(x):
    return f"{x:,}".replace(",", "{,}")


def main():
    inert = load("s1m_pbmc3k_seed_band.json")      # labels_key, 10 seeds
    inj = load("s1m4_pbmc3k_injection.json")       # categorical covariate, 6 seeds
    ver = load("s1m5_pbmc3k_verdict.json")

    q1, q2 = ver["Q1_injection_route"], ver["Q2_published_pair"]
    q3, dis, er = ver["Q3_genuine_injection"], ver["dissociation"], ver["effective_rank_verdict"]
    ni = inj["cross_seed_vanilla_null"]            # null of two vanilla fits (this run)
    ni00 = inert["cross_seed_vanilla_null"]
    kcw = q3["kappa_C_W_corrected"]

    L = [
        "% AUTO-GENERATED by code/make_tabS11.py -- do not edit by hand.",
        "% sources: s1m_pbmc3k_seed_band.json, s1m4_pbmc3k_injection.json, "
        "s1m5_pbmc3k_verdict.json",
        r"\begin{tabular}{@{}lll@{}}",
        r"\toprule",
        r"\textbf{Quantity} & \textbf{Value} & "
        r"\textbf{Reference: family-matched seed null} \\",
        r"\midrule",
        r"\multicolumn{3}{@{}l}{\emph{\textbf{A. The published pair, re-run as "
        r"written (prior registered with \texttt{labels\_key})}}} \\",
        r"Fitted parameters & $%s$ & identical to the vanilla model \\" % num(q1["n_parameters_vanilla"]),
        r"Latent, prior arm vs vanilla arm & $\max|\Delta\Zmat|=0$ & "
        r"bitwise identical, every seed \\",
        r"$\kappa$-$C(W)$, trace form & $%.2f$ & $%.2f\pm%.2f$, $z=%+.2f$ \\"
        % (q2["published_kappa_C_W_trace"], q2["null_mean"], q2["null_sd"], q2["z"]),
        r"Latent effective rank & $%.1f\to%.1f$ & vanilla 10-seed range $%.1f$--$%.1f$ "
        r"($%.1f\pm%.1f$) \\"
        % (q2["published_eff_rank_pair"][0], q2["published_eff_rank_pair"][1],
           q2["vanilla_eff_rank_band"][0], q2["vanilla_eff_rank_band"][1],
           q2["vanilla_eff_rank_mean"], q2["vanilla_eff_rank_sd"]),
        r"\midrule",
        r"\multicolumn{3}{@{}l}{\emph{\textbf{B. The prior registered as a decoder-side "
        r"categorical covariate ($n=%d$ paired seeds)}}} \\" % q3["n_seeds"],
        r"$\kappa$-$C(W)$, trace form & $%.3f\pm%.3f$ & $%.2f\pm%.2f$, $z=%+.1f$ \\"
        % (q3["kappa_C_W_trace"]["mean"], q3["kappa_C_W_trace"]["sd"],
           ni["kappa_trace"]["mean"], ni["kappa_trace"]["sd"], q3["z_vs_null_trace"]),
        r"$\kappa$-$C(W)$, corrected & $%.3f\pm%.3f$ & $%.2f\pm%.2f$, $z=%+.1f$ \\"
        % (kcw["mean"], kcw["sd"], ni["kappa_corrected"]["mean"],
           ni["kappa_corrected"]["sd"], q3["z_vs_null_corrected"]),
        r"$\kappa$-$C(Z)$ & $%.3f\pm%.3f$ & $%.2f\pm%.2f$, $z=%+.1f$ \\"
        % (q3["kappa_C_Z"]["mean"], q3["kappa_C_Z"]["sd"],
           ni["kappa_C_Z"]["mean"], ni["kappa_C_Z"]["sd"], q3["z_vs_null_kappa_C_Z"]),
        r"Latent effective-rank ratio & $%.3f$ & $%.2f\pm%.2f$, $z=%+.1f$ (n.s.) \\"
        % (er["mean_ratio"], er["null_mean"], er["null_sd"], er["z"]),
        r"$D=\kappa$-$C(Z)-\kappa$-$C(W)$ & $%+.3f\pm%.3f$ ($t=%+.1f$) & "
        r"$%+.3f\pm%.3f$, $z=%+.1f$ \\"
        % (dis["mean"], dis["sd"], dis["t_one_sample"],
           dis["null_mean"], dis["null_sd"], dis["z_vs_null"]),
        r"\bottomrule",
        r"\end{tabular}",
    ]

    with open(DEST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {DEST}  ({len(L)} lines)")
    print()
    print("\n".join(L))
    print()
    print("cross-check: labels_key null (10 seeds, 45 pairs) "
          f"kappa_corrected {ni00['kappa_corrected']['mean']:.4f} "
          f"+- {ni00['kappa_corrected']['sd']:.4f}; "
          f"corrected mean {kcw['mean']:.4f} -> "
          f"z {(kcw['mean'] - ni00['kappa_corrected']['mean']) / ni00['kappa_corrected']['sd']:+.1f}")


if __name__ == "__main__":
    main()
