# -*- coding: utf-8 -*-
"""Regenerate Supplementary Table S1 as a reproducible inline LaTeX body.

The published S1 was an external PDF (``supplementary/table_s1_audit.pdf``) whose
generator no longer exists, and it carried only the released trace form.  This
script emits the tabular body in BOTH statistics from the recomputed per-config
data, so the table can never drift from the analysis again.

Reads  : outputs/positive_result/s1f_0of33_recheck.json   (per-config, both forms)
Writes : supplementary/table_s1_audit_body.tex            (\\input by supplementary.tex)

Usage: python code/make_tabS1.py
"""
from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER1 = os.path.abspath(os.path.join(HERE, ".."))
ROOT = os.path.abspath(os.path.join(PAPER1, "..", ".."))
SRC = os.path.join(ROOT, "outputs", "positive_result", "s1f_0of33_recheck.json")
OUT = os.path.join(PAPER1, "supplementary", "table_s1_audit_body.tex")

TISSUE = {"hemo": "H", "neural": "N", "lung": "L"}


def main():
    rows = [r for r in json.load(open(SRC, encoding="utf-8-sig"))["rows"]
            if r.get("status") == "ok"]
    # band carried in the file; use the family-matched corrected per-tissue band
    BAND = {"hemo": (0.971, 1.029), "neural": (0.713, 1.298), "lung": None}

    def regime_of(r):
        k = r["kappa_r2"]
        if k < 0.5:
            return "locked"
        b = BAND.get(r["tissue"])
        if b is None:
            return "no band"
        if k < b[0]:
            return "sub-vanilla"
        if k > b[1]:
            return "expanded"
        return "van-equiv."

    rows.sort(key=lambda r: (r["tissue"], r["kappa_r2"]))

    lines = [
        "% AUTO-GENERATED by code/make_tabS1.py -- do not edit by hand.",
        "% source: outputs/positive_result/s1f_0of33_recheck.json",
        r"\begin{tabular}{@{}llrrrrl@{}}",
        r"\toprule",
        r"\textbf{Config} & \textbf{T} & \multicolumn{2}{c}{\textbf{$\kappa$-$C(W)$}}"
        r" & \multicolumn{2}{c}{\textbf{$C$ (\%)}} & \textbf{Regime} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
        r" & & trace & corrected & trace & corrected & corrected \\",
        r"\midrule",
    ]
    last_t = None
    for r in rows:
        t = r["tissue"]
        if last_t is not None and t != last_t:
            lines.append(r"\midrule")
        last_t = t
        kt, k2 = r["kappa_tr"], r["kappa_r2"]
        name = r["config"].replace("_", r"\_")
        lines.append(
            f"{name} & {TISSUE[t]} & {kt:.3f} & {k2:.3f} & "
            f"{(1 - kt) * 100:+.1f} & {(1 - k2) * 100:+.1f} & {regime_of(r)} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", ""]

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"[wrote] {OUT}  ({len(rows)} configurations)")

    ktr = [r["kappa_tr"] for r in rows]
    kr2 = [r["kappa_r2"] for r in rows]
    print(f"  trace     : {min(ktr):.3f} -- {max(ktr):.3f}   "
          f"C {(1 - max(ktr)) * 100:+.1f} to {(1 - min(ktr)) * 100:+.1f} %")
    print(f"  corrected : {min(kr2):.3f} -- {max(kr2):.3f}   "
          f"C {(1 - max(kr2)) * 100:+.1f} to {(1 - min(kr2)) * 100:+.1f} %")
    n_reg = {}
    for r in rows:
        n_reg[regime_of(r)] = n_reg.get(regime_of(r), 0) + 1
    print("  regimes (corrected, family-matched band):", n_reg)


if __name__ == "__main__":
    main()
