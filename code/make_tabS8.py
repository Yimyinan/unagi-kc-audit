# -*- coding: utf-8 -*-
"""Rebuild Supplementary Table S8 inline, adding the corrected Ridge statistic.

The published S8 is an external PDF: 15 surviving configurations re-audited with the
analytical decoder Jacobian, alongside the Ridge value.  The Ridge column is the
released trace form; the corrected predictability value is available for every one
of the 15 configurations, so both are shown.

Reads  : data/unagi_jacobian_recompute.json          (Jacobian variants A/B)
         outputs/positive_result/s1g_corrected_summaries.json (corrected Ridge kappa)
Writes : supplementary/table_s8_body.tex
Usage  : python code/make_tabS8.py
"""
from __future__ import annotations

import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER1 = os.path.abspath(os.path.join(HERE, ".."))
ROOT = os.path.abspath(os.path.join(PAPER1, "..", ".."))
JAC = os.path.join(PAPER1, "data", "unagi_jacobian_recompute.json")
S1G = os.path.join(ROOT, "outputs", "positive_result", "s1g_corrected_summaries.json")
OUT = os.path.join(PAPER1, "supplementary", "table_s8_body.tex")

TIS = {"hemo": "h", "neural": "n", "lung": "l"}
LOCK = 0.5

# published Ridge trace values, transcribed from the released S8 (its generator is gone)
RIDGE_TR_PUB = {
    "R107_s42": 0.993, "R111_s42": 1.714, "R11_s123": 1.472, "R11_s42": 1.525,
    "R12_s42": 1.776, "R13_s42": 1.791, "R15_s42": 0.916, "R165_s42": 1.844,
    "R16_s42": 1.115, "R84_s42": 1.248, "R9": 0.518, "R1_s123": 0.587,
    "R1_s42": 0.762, "R1_s456": 0.633, "R8_s42": 0.610,
}


def spearman(a, b):
    ra = np.argsort(np.argsort(a)).astype(float)
    rb = np.argsort(np.argsort(b)).astype(float)
    return float(np.corrcoef(ra, rb)[0, 1])


def main():
    jac = json.load(open(JAC, encoding="utf-8-sig"))
    corr = {r["config"]: r["kappa_r2"]
            for r in json.load(open(S1G, encoding="utf-8-sig"))["rows"]}

    rows = []
    for tis, blk in jac["tissues"].items():
        for cfg, v in blk.get("configs", {}).items():
            if cfg not in corr:
                raise SystemExit(f"no corrected kappa for {cfg}")
            rows.append(dict(
                cfg=cfg, tis=tis,
                k_tr=RIDGE_TR_PUB.get(cfg),
                k_r2=corr[cfg],
                jacA=v["kappa_jac"]["first2000_A"],
                jacB=v["kappa_jac"]["first2000_B"],
                jacC=v["C_jac_pct"]["first2000_A"],
            ))
    rows.sort(key=lambda r: (r["tis"], r["cfg"]))

    lines = [
        "% AUTO-GENERATED by code/make_tabS8.py -- do not edit by hand.",
        r"\begin{tabular}{@{}llrrrrr@{}}",
        r"\toprule",
        r"\textbf{Config} & \textbf{T} & \multicolumn{2}{c}{\textbf{Ridge $\kappa$-$C(W)$}}"
        r" & \multicolumn{2}{c}{\textbf{Jacobian $\kappa$}} & \textbf{Jac.\ $C$ (\%)} \\",
        r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
        r" & & trace & corrected & A & B & A \\",
        r"\midrule",
    ]
    last = None
    for r in rows:
        if last is not None and r["tis"] != last:
            lines.append(r"\midrule")
        last = r["tis"]
        lines.append(
            f"{r['cfg'].replace('_', chr(92) + '_')} & {TIS[r['tis']]} & "
            f"{r['k_tr']:.3f} & {r['k_r2']:.4f} & {r['jacA']:.3f} & "
            f"{r['jacB']:.3f} & {r['jacC']:+.1f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    k_tr = np.array([r["k_tr"] for r in rows])
    k_r2 = np.array([r["k_r2"] for r in rows])
    jacA = np.array([r["jacA"] for r in rows])
    print(f"[wrote] {OUT}   n={len(rows)}")
    print(f"  Ridge trace      {k_tr.min():.3f} -- {k_tr.max():.3f}")
    print(f"  Ridge corrected  {k_r2.min():.4f} -- {k_r2.max():.4f}")
    print(f"  Jacobian A       {jacA.min():.3f} -- {jacA.max():.3f}")
    print(f"  locked (kappa<0.5): Ridge-trace {int((k_tr < LOCK).sum())}  "
          f"Ridge-corrected {int((k_r2 < LOCK).sum())}  Jacobian {int((jacA < LOCK).sum())}")
    print(f"  Spearman(Ridge-trace, JacA)      = {spearman(k_tr, jacA):+.3f}")
    print(f"  Spearman(Ridge-corrected, JacA)  = {spearman(k_r2, jacA):+.3f}")


if __name__ == "__main__":
    main()
