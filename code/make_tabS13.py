# -*- coding: utf-8 -*-
"""Generate the body of Supplementary Table S13 from the cross-architecture bands.

Both cross-architecture pairs were originally reported as single runs.  This table puts
each published quantity next to a family-matched reference measured in the same
configuration, so a reader can see what the point estimate is worth.

Panel A (Norman 2019 scVI) -- reference is a *null*: pairs of independent baseline fits
of the same configuration, protocol-matched to the published run (one 200-epoch call;
chunked training is a materially different model and is excluded).  The published
pair's decoder and latent statistics both fall outside it, i.e. the effect is real.

Panel B (family-4 MLP VAE) -- reference is the *paired estimate* over five seeds with
both arms retrained, because there the effect exists by construction and the question is
whether the single published run represents it.  Its released effective-rank ratio does
not.

Reads  : outputs/positive_result/s1p_crossarch_bands_summary.json
Writes : supplementary/table_s13_body.tex
Usage  : python code/make_tabS13.py
"""
from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER1 = os.path.abspath(os.path.join(HERE, ".."))
ROOT = os.path.abspath(os.path.join(PAPER1, "..", ".."))
OUT = os.path.join(ROOT, "outputs", "positive_result")
DEST = os.path.join(PAPER1, "supplementary", "table_s13_body.tex")


def load(n):
    p = os.path.join(OUT, n)
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def verdict(z, k=2.0):
    return ("inside" if abs(z) <= k else "OUTSIDE (2sigma)") + f", $z={z:+.1f}$"


def panel(title, rows, L):
    # a wrapped p-column: an `l` multicolumn cannot break, and these titles are long.
    # NB: no >{...} column syntax -- the `array` package is not loaded in this document.
    L.append(r"\multicolumn{4}{@{}p{0.96\textwidth}@{}}"
             r"{\raggedright\emph{\textbf{%s}}} \\" % title)
    for metric, published, ref, verd in rows:
        L.append(r"%s & %s & %s & %s \\" % (metric, published, ref, verd))


def main():
    d = load("s1p_crossarch_bands_summary.json")
    assert d, "run code/s1p_crossarch_band_summary.py first"
    L = [
        "% AUTO-GENERATED by code/make_tabS13.py -- do not edit by hand.",
        "% source: outputs/positive_result/s1p_crossarch_bands_summary.json",
        r"\begin{tabular}{@{}llll@{}}",
        r"\toprule",
        r"\textbf{Metric} & \textbf{Published} & "
        r"\textbf{Family-matched reference} & \textbf{Verdict} \\",
        r"\midrule",
    ]

    nm = d.get("norman")
    if nm:
        npairs = nm["null_with_published"]["kappa_trace"]["n"]
        rows = []
        for key, label in (("kappa_corrected", r"$\kappa$-$C(W)$, corrected"),
                           ("kappa_trace", r"$\kappa$-$C(W)$, released trace"),
                           ("kappa_C_Z", r"$\kappa$-$C(Z)$"),
                           ("eff_rank_ratio", "Latent effective-rank ratio")):
            v = nm["published_z"]["vs_null_with_published"][key]
            rows.append((label,
                         f"${v['published']:.3f}$",
                         f"${v['null_mean']:.3f}\\pm{v['null_sd']:.3f}$",
                         verdict(v["z"])))
        v = nm["D"]
        rows.append((r"$D=\kappa$-$C(Z)-\kappa$-$C(W)$", f"${v['published']:+.3f}$",
                     f"${v['null']['mean']:+.3f}\\pm{v['null']['sd']:.3f}$",
                     verdict(v["z"])))
        panel(f"A. Norman 2019 scVI, perturbation identity as a decoder covariate "
              f"(published single run; reference = {npairs} pairs of independent "
              f"single-protocol baseline fits. This baseline-only null is the "
              f"weaker test and its latent-side verdicts move with the composition "
              f"of the pool; the paired design in panel C is the primary one.)",
              rows, L)
        L.append(r"\midrule")

    f4 = d.get("family4")
    if f4:
        rows = []
        for label, pub, band_key in (
                (r"$\kappa$-$C(W)$, corrected", f4["published"]["kappa_corrected"],
                 "kappa_corrected"),
                (r"$\kappa$-$C(W)$, released trace", f4["published"]["kappa_trace"],
                 "kappa_trace"),
                (r"$\kappa$-$C(Z)$", f4["published"]["kappa_C_Z"], "kappa_C_Z"),
                ("Latent effective-rank ratio", f4["published"]["eff_rank_ratio"],
                 "eff_rank_ratio")):
            b = f4["paired"][band_key]
            z = (pub - b["mean"]) / b["sd"]
            rows.append((label, f"${pub:.3f}$",
                         f"${b['mean']:.3f}\\pm{b['sd']:.3f}$",
                         verdict(z)))
        v = f4["D"]
        rows.append((r"$D=\kappa$-$C(Z)-\kappa$-$C(W)$",
                     f"${v['paired']['mean']:+.3f}\\pm{v['paired']['sd']:.3f}$ "
                     f"($t={v['t']:+.1f}$)",
                     f"${v['null']['mean']:+.3f}\\pm{v['null']['sd']:.3f}$",
                     verdict(v["z"])))
        panel("B. Family-4 MLP VAE, decoder-only conditioning "
              "(published single run; reference = the paired 5-seed estimate, right "
              "column of the paired rows)", rows, L)
        L.append(r"\midrule")
        L.append(r"\multicolumn{4}{@{}p{0.96\textwidth}@{}}{\raggedright\footnotesize\emph{Panel B rows 1--4: "
                 r"the published value is tested against the paired seed estimate; "
                 r"the $D$ row is tested against a family-matched baseline-pair null "
                 r"as in panel A.}} \\")

    # ---------------- panel C: the paired design's effect scatter ---------------
    ip = load("s1n3_norman_injected_paired.json")
    if ip and ip.get("per_seed"):
        key = "paired_completed" if ip.get("n_paired_completed") else "paired_all"
        n = ip["n_paired"] if key == "paired_all" else ip["n_paired_completed"]
        rows = []
        for name, label in (
                ("kappa_C_W_corrected", r"$\kappa$-$C(W)$, corrected"),
                ("kappa_C_W_trace", r"$\kappa$-$C(W)$, released trace"),
                ("kappa_C_Z", r"$\kappa$-$C(Z)$"),
                ("eff_rank_ratio", "Latent effective-rank ratio"),
                ("D", r"$D=\kappa$-$C(Z)-\kappa$-$C(W)$")):
            d = ip[key].get(name)
            if not d or not d.get("n"):
                continue
            pub = ip["published_single_pair"].get(name)
            # NB: keep \pm *inside* the math delimiters -- emitting "$\pm x$" next to a
            # separate "$mean$" closes math mode early and renders "±x" literally.
            sd_txt = f"\\pm{d['sd']:.3f}" if d.get("sd") is not None else ""
            stat = d.get("t_vs_1")
            if stat is None:
                stat = d.get("t_vs_0")
            stat_txt = f" ($t={stat:+.1f}$)" if stat is not None else ""
            good = pub is not None and d.get("sd")
            rows.append((label,
                         f"${pub:+.3f}$" if pub is not None else "--",
                         f"${d['mean']:+.3f}{sd_txt}$ ({n} seeds){stat_txt}",
                         verdict((pub - d["mean"]) / d["sd"]) if good
                         else "not computed"))
        panel("C. Norman scVI, paired design: both arms fitted at the same seed, so the "
              "baseline scatter cancels and the right column is the effect itself",
              rows, L)
        L.append(r"\midrule")
        L.append(r"\multicolumn{4}{@{}p{0.96\textwidth}@{}}{\raggedright\footnotesize\emph{Panel C: the verdict compares the published single pair with the paired effect estimate; a non-unity effect scatter means one run does not pin the configuration down.}} \\")

    L += [r"\bottomrule", r"\end{tabular}"]
    with open(DEST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {DEST}")
    print("\n".join(L))


if __name__ == "__main__":
    main()
