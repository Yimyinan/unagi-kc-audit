"""Regenerate Supplementary Table S8 over all 33 configurations.

Recreated 2026-10-08.  The published S8 covered 15 configurations and explained the rest as
"Ridge-only because their checkpoints were not retained"; all 33 checkpoints are on disk and
were re-audited (code/jacobian_reaudit_33.py), so the table is now complete.

Reads  : data/unagi_jacobian_reaudit_33.json
         _infra/artifacts/outputs/positive_result/s1g_corrected_summaries.json
Writes : supplementary/table_s8_body_33.tex   (with --out=)
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER1 = os.path.abspath(os.path.join(HERE, ".."))
JAC = os.path.join(PAPER1, "data", "unagi_jacobian_reaudit_33.json")
S1G = r"F:\UNAGI_Project\_infra\artifacts\outputs\positive_result\s1g_corrected_summaries.json"
TIS = {"hemo": "Hematopoietic", "neural": "Neural crest", "lung": "Lung fibrosis"}
LOCK = 0.5


def spearman(a, b):
    ra = np.argsort(np.argsort(a)).astype(float)
    rb = np.argsort(np.argsort(b)).astype(float)
    return float(np.corrcoef(ra, rb)[0, 1])


def main():
    jac = json.load(open(JAC, encoding="utf-8"))
    corr = {}
    if os.path.exists(S1G):
        for r in json.load(open(S1G, encoding="utf-8-sig"))["rows"]:
            corr[r["config"]] = r["kappa_r2"]
    rows = []
    for tis, blk in jac["tissues"].items():
        for cfg, v in blk["configs"].items():
            rows.append({"cfg": cfg, "tis": tis, "k": corr.get(cfg),
                         "a": v["kappa_jac_A"], "b": v["kappa_jac_B"], "c": v["C_jac_pct_A"]})
    rows.sort(key=lambda r: (list(TIS).index(r["tis"]), r["cfg"]))

    L = ["% AUTO-GENERATED by code/make_tabS8_33.py -- do not edit by hand.",
         r"\begin{tabular}{@{}llrrrrc@{}}", r"\toprule",
         r"\textbf{Config} & \textbf{Tissue} & \textbf{Ridge $\kappa$} & "
         r"\textbf{Jac.\ $\kappa$ (A)} & \textbf{Jac.\ $\kappa$ (B)} & "
         r"\textbf{Jac.\ $C$ (\%)} & \textbf{Locked} \\", r"\midrule"]
    A, B, K, last = [], [], [], None
    for r in rows:
        if last is not None and r["tis"] != last:
            L.append(r"\midrule")
        last = r["tis"]
        kt = ("%.3f" % r["k"]) if r["k"] is not None else "---"
        L.append(r"%s & %s & %s & %.3f & %.3f & %+.1f & \textbf{no} \\"
                 % (r["cfg"].replace("_", r"\_"), TIS[r["tis"]], kt, r["a"], r["b"], r["c"]))
        A.append(r["a"]); B.append(r["b"])
        if r["k"] is not None:
            K.append(r["k"])
    A, B, K = np.array(A), np.array(B), np.array(K)
    rho = spearman(K, A) if len(K) == len(A) else float("nan")
    L += [r"\midrule",
          (r"\multicolumn{7}{l}{\footnotesize %d configurations; \textbf{0 locked under either} "
           r"estimator; minimum $\kappa_{\mathrm{jac}}=%.2f$; agreement %d/%d; "
           r"Spearman $\rho=%+.2f$.} \\"
           % (len(A), A.min(), len(A), len(A), rho)),
          r"\bottomrule", r"\end{tabular}", ""]
    out = os.path.join(PAPER1, "supplementary", "table_s8_body_33.tex")
    for a in sys.argv[1:]:
        if a.startswith("--out="):
            out = a.split("=", 1)[1]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(L))
    print("[wrote] %s  n=%d" % (out, len(rows)))
    print("  Jacobian A %.3f-%.3f locked %d/%d" % (A.min(), A.max(), int((A < LOCK).sum()), len(A)))
    print("  Jacobian B %.3f-%.3f locked %d/%d" % (B.min(), B.max(), int((B < LOCK).sum()), len(B)))
    print("  Ridge      %.3f-%.3f locked %d/%d (n=%d)" % (K.min(), K.max(), int((K < LOCK).sum()), len(K), len(K)))
    print("  Spearman(Ridge, JacA) = %+.3f" % rho)


if __name__ == "__main__":
    main()
